const languageMeta = {
  he: { dir: "rtl", locale: "he_IL" },
  en: { dir: "ltr", locale: "en_US" },
  ru: { dir: "ltr", locale: "ru_RU" }
};

const supportedLanguages = Object.keys(translations);

const setMeta = (selector, value) => {
  const element = document.querySelector(selector);
  if (element) element.setAttribute("content", value);
};

const applyLanguage = (language, updateAddress = true) => {
  const selected = supportedLanguages.includes(language) ? language : "he";
  const dictionary = translations[selected];
  const meta = languageMeta[selected];

  document.documentElement.lang = selected;
  document.documentElement.dir = meta.dir;
  document.title = dictionary.pageTitle;
  setMeta('meta[name="description"]', dictionary.pageDescription);
  setMeta('meta[property="og:title"]', dictionary.pageTitle);
  setMeta('meta[property="og:description"]', dictionary.pageDescription);
  setMeta('meta[property="og:locale"]', meta.locale);
  setMeta('meta[name="twitter:title"]', dictionary.pageTitle);
  setMeta('meta[name="twitter:description"]', dictionary.pageDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try {
    window.localStorage.setItem("structor-showcase-language", selected);
  } catch {
    // The site still works when storage is unavailable.
  }

  if (updateAddress) {
    const url = new URL(window.location.href);
    if (selected === "he") url.searchParams.delete("lang");
    else url.searchParams.set("lang", selected);
    window.history.replaceState({}, "", `${url.pathname}${url.search}${url.hash}`);
  }
};

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

document.querySelectorAll("[data-site-tab]").forEach((button) => {
  button.addEventListener("click", () => {
    const target = button.dataset.siteTab;
    document.querySelectorAll("[data-site-tab]").forEach((tab) => {
      tab.classList.toggle("is-active", tab === button);
    });
    document.querySelector(`[data-site-panel="${target}"]`)?.scrollIntoView({ behavior: "smooth", block: "start" });
  });
});

document.querySelectorAll("[data-service-tab]").forEach((button) => {
  button.addEventListener("click", () => {
    const target = button.dataset.serviceTab;
    document.querySelectorAll("[data-service-tab]").forEach((tab) => {
      const active = tab === button;
      tab.classList.toggle("is-active", active);
      tab.setAttribute("aria-selected", String(active));
    });
    document.querySelectorAll("[data-service-panel]").forEach((panel) => {
      panel.classList.toggle("is-active", panel.dataset.servicePanel === target);
    });
  });
});

const params = new URLSearchParams(window.location.search);
let initialLanguage = params.get("lang");

if (!supportedLanguages.includes(initialLanguage)) {
  try {
    initialLanguage = window.localStorage.getItem("structor-showcase-language");
  } catch {
    initialLanguage = null;
  }
}

applyLanguage(supportedLanguages.includes(initialLanguage) ? initialLanguage : "he", false);
