let currentLanguage = "he";

const setText = (selector, value) => {
  const element = document.querySelector(selector);
  if (element) element.setAttribute("content", value);
};

const applyLanguage = (language) => {
  currentLanguage = language;
  const dictionary = translations[language];
  const isHebrew = language === "he";

  document.documentElement.lang = language;
  document.documentElement.dir = isHebrew ? "rtl" : "ltr";
  document.title = dictionary.title;
  setText('meta[name="description"]', dictionary.description);
  setText('meta[property="og:title"]', isHebrew ? "אינסטלטור ודודי שמש בטבריה" : "Сантехник и солнечные бойлеры в Тверии");
  setText('meta[property="og:description"]', isHebrew ? "התקנת דודי שמש, חיבור מכונות כביסה ומדיחים, צנרת ועבודות אינסטלציה. טלפון: 053 361 3100." : "Монтаж солнечных бойлеров, подключение стиральных и посудомоечных машин, водопровод и сантехника. Телефон: 053 361 3100.");
  setText('meta[property="og:locale"]', isHebrew ? "he_IL" : "ru_RU");

  document.querySelectorAll("[data-key]").forEach((element) => {
    const value = dictionary[element.dataset.key];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-whatsapp-link]").forEach((link) => {
    link.href = `https://wa.me/972533613100?text=${encodeURIComponent(whatsappMessages[language])}`;
  });

  const toggle = document.querySelector("[data-language-toggle]");
  if (toggle) {
    toggle.setAttribute("aria-label", isHebrew ? "לעבור לרוסית" : "Переключить на иврит");
  }
};

document.querySelector("[data-language-toggle]")?.addEventListener("click", () => {
  applyLanguage(currentLanguage === "he" ? "ru" : "he");
});

const copyButton = document.querySelector("[data-copy]");

if (copyButton) {
  copyButton.addEventListener("click", async () => {
    const number = copyButton.getAttribute("data-copy");
    const label = copyButton.querySelector(".copy-button__label");
    const originalText = translations[currentLanguage].copyButton;

    try {
      await navigator.clipboard.writeText(number);
      copyButton.classList.add("is-copied");
      if (label) label.textContent = translations[currentLanguage].copiedButton;
      window.setTimeout(() => {
        copyButton.classList.remove("is-copied");
        if (label) label.textContent = originalText;
      }, 1800);
    } catch {
      window.location.href = `tel:${number.replace(/\s/g, "")}`;
    }
  });
}

applyLanguage("he");
