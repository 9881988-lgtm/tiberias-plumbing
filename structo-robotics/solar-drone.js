const solarDirectionByLanguage = {
  he: "rtl",
  en: "ltr",
  ru: "ltr"
};

const solarLanguageButtons = document.querySelectorAll("[data-set-lang]");
const solarTranslatedElements = document.querySelectorAll("[data-solar-i18n]");

function setSolarLanguage(language) {
  const dictionary = solarTranslations[language] || solarTranslations.he;
  solarTranslatedElements.forEach((element) => {
    const key = element.dataset.solarI18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.documentElement.lang = language;
  document.documentElement.dir = solarDirectionByLanguage[language];

  solarLanguageButtons.forEach((button) => {
    const isActive = button.dataset.setLang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("structo-language", language);
}

solarLanguageButtons.forEach((button) => {
  button.addEventListener("click", () => setSolarLanguage(button.dataset.setLang));
});

const requestedSolarLanguage = new URLSearchParams(window.location.search).get("lang");
const savedSolarLanguage = localStorage.getItem("structo-language");
setSolarLanguage(
  requestedSolarLanguage && solarTranslations[requestedSolarLanguage]
    ? requestedSolarLanguage
    : savedSolarLanguage && solarTranslations[savedSolarLanguage]
      ? savedSolarLanguage
      : "he"
);
