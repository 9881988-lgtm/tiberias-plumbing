const directionByLanguage = {
  he: "rtl",
  en: "ltr",
  ru: "ltr"
};

const languageButtons = document.querySelectorAll("[data-set-lang]");
const translatedElements = document.querySelectorAll("[data-i18n]");

function setLanguage(language) {
  const dictionary = translations[language] || translations.he;
  translatedElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.documentElement.lang = language;
  document.documentElement.dir = directionByLanguage[language];

  languageButtons.forEach((button) => {
    const isActive = button.dataset.setLang === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("structo-language", language);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.setLang));
});

const savedLanguage = localStorage.getItem("structo-language");
setLanguage(savedLanguage && translations[savedLanguage] ? savedLanguage : "he");
