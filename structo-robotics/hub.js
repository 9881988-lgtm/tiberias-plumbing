const hubDirectionByLanguage = {
  he: "rtl",
  en: "ltr",
  ru: "ltr"
};

const hubLanguageButtons = document.querySelectorAll("[data-set-hub-lang]");
const hubTranslatedElements = document.querySelectorAll("[data-hub-i18n]");
const supportedHubLanguages = Object.keys(hubTranslations);

function getInitialHubLanguage() {
  const urlLanguage = new URLSearchParams(window.location.search).get("lang");
  if (supportedHubLanguages.includes(urlLanguage)) return urlLanguage;
  const saved = localStorage.getItem("structor-language");
  return supportedHubLanguages.includes(saved) ? saved : "he";
}

function localizeLandingLinks(language) {
  document.querySelectorAll("[data-localized-url]").forEach((link) => {
    const baseUrl = link.dataset.localizedUrl;
    if (!baseUrl) return;
    if (language === "he") {
      link.href = baseUrl;
      return;
    }
    link.href = `${baseUrl}?lang=${encodeURIComponent(language)}`;
  });
}

function setHubLanguage(language) {
  const selectedLanguage = supportedHubLanguages.includes(language) ? language : "he";
  const dictionary = hubTranslations[selectedLanguage];

  hubTranslatedElements.forEach((element) => {
    const value = dictionary[element.dataset.hubI18n];
    if (value) element.textContent = value;
  });

  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = hubDirectionByLanguage[selectedLanguage];

  hubLanguageButtons.forEach((button) => {
    const isActive = button.dataset.setHubLang === selectedLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localizeLandingLinks(selectedLanguage);
  localStorage.setItem("structor-language", selectedLanguage);
}

hubLanguageButtons.forEach((button) => {
  button.addEventListener("click", () => setHubLanguage(button.dataset.setHubLang));
});

setHubLanguage(getInitialHubLanguage());
